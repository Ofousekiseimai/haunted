const LNG_CENTER = 23.5;
const SCALE = 0.28;

function project(coords: [number, number][]): [number, number][] {
  return coords.map(([lng, lat]) => [
    (lng - LNG_CENTER) * SCALE,
    (lat - LAT_CENTER) * SCALE,
  ]);
}

